}
Add-Result -Result @{ name = 'probe-empty'; command = '--test-case-gui'; argv = @('--test-case-gui', $probeScripts['empty']); exit_code = $result.ExitCode; timed_out = $result.TimedOut; ok = $probeOk; diagnostics = if ($result.ContainsKey('TimeoutDiagnostics')) { $result.TimeoutDiagnostics.Root } else { $null }; log = $result.StdoutLog }

# Probe 4: an aborted test case must exit 1 and record the abort in its report.
$abortedDataRoot = Join-Path $probeRoot 'data-aborted'
$result = Invoke-TestflowProbe -Name 'aborted' -ScriptPath $probeScripts['aborted'] -DataRoot $abortedDataRoot
$probeReports = @(Get-ChildItem -LiteralPath (Join-Path $abortedDataRoot 'reports') -File -ErrorAction SilentlyContinue)
$probeOk = $false
if ($result.TimedOut) {
    Add-Failure "probe aborted timed out after ${GuiTimeoutSeconds}s; $($result.TerminationSummary) (diagnostics $($result.TimeoutDiagnostics.Root); log $($result.StdoutLog))"
} elseif ($result.ExitCode -ne 1) {
    Add-Failure "probe aborted: expected exit 1 for an aborted test case, got exit $($result.ExitCode); a crash or unexpected exit is not a correct rejection (log $($result.StdoutLog))"
} elseif ($probeReports.Count -ne 1) {
    Add-Failure "probe aborted: expected one report under $abortedDataRoot, found $($probeReports.Count) (log $($result.StdoutLog))"
} else {
    $abortedReportText = [IO.File]::ReadAllText($probeReports[0].FullName)
    if ($abortedReportText -notmatch 'Test case aborted!|abort step:') {
        Add-Failure "probe aborted: report '$($probeReports[0].Name)' does not record the abort"
    } else {
        $probeOk = $true
        Write-Host "probe aborted passed (exit $($result.ExitCode), report '$($probeReports[0].Name)' records the abort)"
    }
}
Add-Result -Result @{ name = 'probe-aborted'; command = '--test-case-gui'; argv = @('--test-case-gui', $probeScripts['aborted']); exit_code = $result.ExitCode; timed_out = $result.TimedOut; ok = $probeOk; diagnostics = if ($result.ContainsKey('TimeoutDiagnostics')) { $result.TimeoutDiagnostics.Root } else { $null }; log = $result.StdoutLog }

# ---------------------------------------------------------------------------
# Diagnostics
# Only this run's own development profile is collected: the exact <Local>/MuseScore/<app name>
# directory the packaged application wrote to. Other profiles on the host are never read.
$appLogRoot = $profilePlan.LogDirectory
if (Test-Path -LiteralPath $appLogRoot -PathType Container) {
    $appLogs = @(Get-ChildItem -LiteralPath $appLogRoot -Recurse -File -ErrorAction SilentlyContinue)
    foreach ($log in $appLogs) {
        Copy-Item -LiteralPath $log.FullName -Destination (Join-Path $logRoot ("app-" + $log.Name)) -Force -ErrorAction SilentlyContinue
    }
    Write-Host "collected $($appLogs.Count) application log file(s) from $appLogRoot"
} else {
    Write-Host "no application logs under $appLogRoot (the application did not create its profile directory)"
}

# Every runtime log and the machine-readable report live under
# <OutputDirectory>/logs so the workflow can upload that single directory.
$reportPath = Join-Path $logRoot 'runtime-tests.json'
[IO.File]::WriteAllText(
    $reportPath,
    (ConvertTo-Json -InputObject @($script:Results) -Depth 6),
    [Text.UTF8Encoding]::new($false))
Write-Host "report: $reportPath"

Write-Host ''
if ($script:Failures.Count -gt 0) {
    Write-Host "test-windows-package: FAILED ($($script:Failures.Count) problem(s))"
    foreach ($failure in $script:Failures) {
        Write-Host "  - $failure"
    }
    exit 1
}

Write-Host 'test-windows-package: OK'
exit 0
