#!/usr/bin/env pwsh
# SPDX-License-Identifier: GPL-3.0-only
#
# MuseScore fork CI: fresh-runner Windows package runtime helper.
#
# Runs on a runner that has NO Qt installation. It verifies the downloaded
# package against its manifest/checksums, extracts it outside the source and
# build trees, then exercises the real installed application:
#
#   1. structural checks (executable, Qt runtime, resources, installed tests)
#   2. bounded `--version` check with output assertion (a spawn is not success)
#   3. bounded headless exports through the revision's `-o` converter path: a PDF
#      (exercises layout, rendering and font embedding) and a score container
#      (MSCZ opened as a ZIP and required to carry the score XML)
#   4. GUI testflow: mandatory TC11 + TC14, and exact feature TC15 when its source fixture is
#      present, through `--test-case-gui`: the reviewed script from the source checkout
#      must be present, the run must exit 0, and it must leave exactly one
#      testflow report under the helper-owned MUSE_TESTFLOW_DATA_PATH whose declared test
#      case name and step list match the reviewed script and in which every declared step
#      finished
#   5. bounded probes of the testflow report/status contract, run against the installed
#      application with tiny trusted scripts generated by this helper
#
# Developer Qt/QML environment overrides are cleared explicitly for every child
# process, and on a real Windows host the application's search path is rebuilt to
# the package directory plus the Windows system directories. The first-run profile
# is prepared in the profile the packaged application actually opens, and this
# helper never overwrites or deletes an existing one (see the first-run profile
# section below). Every process is timeout-bounded and its tree is killed on
# timeout, with stdout/stderr and the application's own logs retained.
#
# What this proves: the distribution package is self-contained enough to start,
# export, and run its GUI regression tests without a developer Qt install, in a
# clean development profile on a fresh runner.
# What it does NOT prove: behavior on a minimal end-user Windows installation,
# or NVDA/JAWS/physical Braille-device announcement behavior.
#
# Usage:
#   pwsh -File buildscripts/ci/fork/test-windows-package.ps1 `
#       -ArtifactDirectory <dir with zip + SHA256SUMS.txt + build-manifest.json> `
#       -SourceDirectory   <same source_sha checkout; fixtures only> `
#       -OutputDirectory   <logs, profile sandbox, extraction, report>
#
#   pwsh -File buildscripts/ci/fork/test-windows-package.ps1 -ExportProfilePlan `
#       -SourceDirectory <checkout> -OutputDirectory <dir>
#       prints the resolved first-run profile contract for that directory's profile sandbox as
#       JSON. Testability hook: it applies the same hosted-runner guard and existing-profile
#       refusal as a real run, without the sandbox being recreated first.

[CmdletBinding()]
param(
    [string] $ArtifactDirectory,
    [string] $SourceDirectory,
    [string] $OutputDirectory,
    [int] $VersionTimeoutSeconds = 60,
    [int] $ExportTimeoutSeconds = 300,
    [int] $GuiTimeoutSeconds = 600,
    # Testability hook (see the "Testability hook" section): resolves and validates the first-run
    # profile contract for the -OutputDirectory sandbox instead of running the package.
    [switch] $ExportProfilePlan
)

$ErrorActionPreference = 'Stop'
Set-StrictMode -Version Latest

$script:IsWindowsHost = ($env:OS -eq 'Windows_NT')
$script:Failures = @()
$script:Results = @()

$script:MandatoryTestScripts = @(
    'TC11_CommandPaletteDialog.js'
    'TC14_CommandPaletteAnnounce.js'
)
# TC15 is a reviewed feature test, not part of the base CI contract. It is selected only when
# this exact source fixture is present in the source checkout; no source-owned list or glob can
# opt arbitrary tests into the runtime gate.
$script:FeatureTestScriptName = 'TC15_RegionEntryAnnounce.js'
$script:RequiredTestScripts = @()

# The testflow runner records each executed test case under
# <MUSE_TESTFLOW_DATA_PATH>/reports. Pointing that at the helper's own output directory
# makes the record of the run helper-owned evidence instead of a path inside the package.
$script:TestflowDataRelative = 'testflow-data'

# Every wait in this helper is bounded. Besides the timeout of the observed process these are the
# deadline for confirming that the termination of a timed-out process tree actually happened, and
# the deadline for draining the child's redirected output: a descendant process that inherited the
# pipe keeps the read open indefinitely, and a test must never wait on that.
$script:KillTimeoutSeconds = 10
$script:OutputDrainSeconds = 10
$script:TimeoutDiagnosticsSeconds = 30
$script:TimeoutDiagnosticsMaxBytes = 256MB
$script:ProcessSnapshotTimeoutSeconds = 5

# Profile sandbox layout used for the POSIX fixture host and for the plan testability hook; a real
# Windows run uses the known folders instead of this sandbox (see the first-run profile section).
$script:ProfileSandboxRoamingRelative = 'profile/AppData/Roaming'
$script:ProfileSandboxLocalRelative = 'profile/AppData/Local'

# Where the packaged application keeps its state, from this revision's own code:
# QSettings uses IniFormat/UserScope, whose Windows path is
# <Roaming known folder>/<Organization>/<ApplicationName>.ini (framework/global/settings.cpp;
# Organization "MuseScore" and ApplicationName from version metadata, src/app/main.cpp), and the
# application-local profile holding the session and logs is
# QStandardPaths::AppLocalDataLocation = <Local known folder>/<Organization>/<ApplicationName>
# (framework/global/internal/globalconfiguration.cpp, framework/global/globalmodule.cpp writes
# logs under "<userAppDataPath>/logs").
#
# Qt resolves both through the Windows known folders (SHGetKnownFolderPath), so APPDATA and
# LOCALAPPDATA set for a child process do NOT redirect them. The helper therefore seeds the INI at
# the real path, refuses to run when that profile already exists, and takes its isolation from the
# fresh hosted VM the workflow provides - not from environment redirection.

# Developer-only Qt/QML environment overrides that must not leak into the test.
$script:QtEnvironmentVariables = @(
    'QTDIR'
    'QT_PLUGIN_PATH'
    'QT_QPA_PLATFORM_PLUGIN_PATH'
    'QML_IMPORT_PATH'
    'QML2_IMPORT_PATH'
    'QT_QML_IMPORT_PATH'
    'QT_QPA_PLATFORM'
    'QT_QUICK_BACKEND'
    'QT_SCALE_FACTOR'
    'MUSE_TESTFLOW_SCRIPTS_PATH'
    'MUSE_TESTFLOW_FILES_PATH'
)

function Fail {
    param([Parameter(Mandatory = $true)][string] $Message)
    throw "test-windows-package: $Message"
}

function Add-Failure {
    param([Parameter(Mandatory = $true)][string] $Message)
    Write-Host "FAIL: $Message"
    $script:Failures += $Message
}

function Add-Result {
    param([Parameter(Mandatory = $true)][hashtable] $Result)
    $script:Results += $Result
}

function Write-Section {
    param([Parameter(Mandatory = $true)][string] $Message)
    Write-Host "== $Message"
}

function Get-JsonField {
    param(
        [Parameter(Mandatory = $false)] $Object,
        [Parameter(Mandatory = $true)][string] $Name
    )

    if ($null -eq $Object) {
        return $null
    }

    $property = $Object.PSObject.Properties[$Name]
    if ($null -eq $property) {
        return $null
    }

    return $property.Value
}

function Get-Sha256 {
    param([Parameter(Mandatory = $true)][string] $Path)
    if (-not (Test-Path -LiteralPath $Path -PathType Leaf)) {
        Fail "cannot hash missing file: $Path"
    }
    return (Get-FileHash -LiteralPath $Path -Algorithm SHA256).Hash.ToLowerInvariant()
}

function Resolve-RequiredDirectory {
    param(
        [Parameter(Mandatory = $true)][string] $Path,
        [Parameter(Mandatory = $true)][string] $Name
    )

    if ([string]::IsNullOrWhiteSpace($Path)) {
        Fail "-$Name is required"
    }
    if (-not (Test-Path -LiteralPath $Path -PathType Container)) {
        Fail "-$Name directory not found: $Path"
    }
    return (Resolve-Path -LiteralPath $Path).Path.TrimEnd([IO.Path]::DirectorySeparatorChar, [IO.Path]::AltDirectorySeparatorChar)
}

function Resolve-FullPath {
    param([Parameter(Mandatory = $true)][string] $Path)
    return [IO.Path]::GetFullPath($Path).TrimEnd([IO.Path]::DirectorySeparatorChar, [IO.Path]::AltDirectorySeparatorChar)
}

function Test-PathInside {
    param(
        [Parameter(Mandatory = $true)][string] $Parent,
        [Parameter(Mandatory = $true)][string] $Child
    )

    $parentFull = Resolve-FullPath -Path $Parent
    $childFull = Resolve-FullPath -Path $Child
    $separator = [IO.Path]::DirectorySeparatorChar
    return $childFull.StartsWith("$parentFull$separator", [StringComparison]::OrdinalIgnoreCase)
}

function Assert-ZipEntrySafe {
    param([Parameter(Mandatory = $true)][string] $EntryName)

    $normalized = $EntryName -replace '\\', '/'
    if ([string]::IsNullOrWhiteSpace($normalized)) {
        Fail 'path is empty'
    }
    if ($normalized.StartsWith('/') -or $normalized -match '^[A-Za-z]:') {
        Fail "absolute path is not allowed: $EntryName"
    }
    foreach ($segment in $normalized.Split('/')) {
        if ($segment -eq '..') {
            Fail "path escapes the extraction root: $EntryName"
        }
    }
}

function Read-VersionCmake {
    param([Parameter(Mandatory = $true)][string] $Path)

    if (-not (Test-Path -LiteralPath $Path -PathType Leaf)) {
        return $null
    }

    $text = Get-Content -LiteralPath $Path -Raw
    $values = @{}
    foreach ($name in @('MUSE_APP_NAME_MACHINE_READABLE', 'MUSE_APP_VERSION_MAJOR', 'MUSE_APP_VERSION_MINOR', 'MUSE_APP_VERSION_PATCH', 'MUSE_APP_UNSTABLE')) {
        $pattern = "(?m)^\s*set\(\s*$name\s+""?([^""\)\r\n]+)""?\s*\)"
        $match = [regex]::Match($text, $pattern)
        if ($match.Success) {
            $values[$name] = $match.Groups[1].Value.Trim()
        }
    }
    return $values
}

function Get-GitHead {
    param([Parameter(Mandatory = $true)][string] $Directory)

    if (-not (Test-Path -LiteralPath (Join-Path $Directory '.git'))) {
        Fail "-SourceDirectory is not a git checkout (no .git): $Directory"
    }
    $head = & git -C $Directory rev-parse HEAD 2>&1
    if ($LASTEXITCODE -ne 0) {
        Fail "git rev-parse HEAD failed in $Directory (exit $LASTEXITCODE): $head"
    }
    return ($head | Select-Object -First 1).ToString().Trim()
}

function Get-EnvValue {
    param(
        [Parameter(Mandatory = $true)][System.Diagnostics.ProcessStartInfo] $StartInfo,
        [Parameter(Mandatory = $true)][string] $Name
    )

    foreach ($key in @($StartInfo.Environment.Keys)) {
        if ($key.Equals($Name, [StringComparison]::OrdinalIgnoreCase)) {
            return $StartInfo.Environment[$key]
        }
    }
    return $null
}

function Remove-EnvValue {
    param(
        [Parameter(Mandatory = $true)][System.Diagnostics.ProcessStartInfo] $StartInfo,
        [Parameter(Mandatory = $true)][string] $Name
    )

    foreach ($key in @($StartInfo.Environment.Keys)) {
        if ($key.Equals($Name, [StringComparison]::OrdinalIgnoreCase)) {
            $StartInfo.Environment.Remove($key) | Out-Null
        }
    }
}

function Set-EnvValue {
    param(
        [Parameter(Mandatory = $true)][System.Diagnostics.ProcessStartInfo] $StartInfo,
        [Parameter(Mandatory = $true)][string] $Name,
        [Parameter(Mandatory = $true)][string] $Value
    )

    Remove-EnvValue -StartInfo $StartInfo -Name $Name
    $StartInfo.Environment[$Name] = $Value
}

function Get-DevelopmentProfileName {
    <#
        The application name that QSettings and AppLocalDataLocation use, derived from the same
        source metadata the application itself compiles in: src/app/main.cpp sets
        QCoreApplication::setApplicationName(MUSE_APP_NAME_MACHINE_READABLE MUSE_APP_VERSION_MAJOR
        "Development") under MUSE_APP_UNSTABLE. The development channel is the only channel this
        fork pipeline builds, so a checkout that is not built as the development channel is
        refused instead of guessing which profile the package would use.
    #>
    param([Parameter(Mandatory = $true)][hashtable] $Version)

    foreach ($name in @('MUSE_APP_NAME_MACHINE_READABLE', 'MUSE_APP_VERSION_MAJOR', 'MUSE_APP_UNSTABLE')) {
        if (-not $Version.ContainsKey($name) -or [string]::IsNullOrWhiteSpace([string] $Version[$name])) {
            Fail "version.cmake does not declare $name; the application profile name cannot be derived"
        }
    }

    if ([string] $Version['MUSE_APP_UNSTABLE'] -ne 'ON') {
        Fail ("MUSE_APP_UNSTABLE is '$($Version['MUSE_APP_UNSTABLE'])', not ON: this pipeline packages the development " +
              'channel and must not seed the profile of another channel')
    }

    return "$($Version['MUSE_APP_NAME_MACHINE_READABLE'])$($Version['MUSE_APP_VERSION_MAJOR'])Development"
}

function Resolve-ProfilePlan {
    <#
        Resolves the profile contract for the packaged application from the known-folder roots it
        will actually use, and refuses to reuse an existing development profile. The returned
        plan is:

          SettingsDirectory          <Roaming>/MuseScore
          SettingsFilePath           <Roaming>/MuseScore/<application name>.ini
          ProfileDirectory           <Local>/MuseScore/<application name>
          LogDirectory               <Local>/MuseScore/<application name>/logs
          ApplicationDataRoot        <Roaming>
          LocalApplicationDataRoot   <Local>
          RedirectEnvironment        $true only for the POSIX fixture sandbox
          Refusals                   existing paths this helper will not overwrite

        On Windows the two roots are the real known folders, so the seeded file is the one the
        application opens and Refusals is a hard stop: the helper never overwrites or deletes a
        profile it did not create. The fixture sandbox under -OutputDirectory passes
        -RedirectEnvironment because there the roots are handed to the stub through APPDATA and
        LOCALAPPDATA.
    #>
    param(
        [Parameter(Mandatory = $true)][string] $RoamingRoot,
        [Parameter(Mandatory = $true)][string] $LocalRoot,
        [Parameter(Mandatory = $true)][string] $ProfileName,
        [Parameter(Mandatory = $false)][bool] $RedirectEnvironment = $false
    )

    foreach ($folder in @(
            [pscustomobject]@{ Name = 'ApplicationData'; Path = $RoamingRoot },
            [pscustomobject]@{ Name = 'LocalApplicationData'; Path = $LocalRoot })) {
        if ([string]::IsNullOrWhiteSpace($folder.Path)) {
            Fail "the $($folder.Name) known folder resolved to an empty path; the profile location is unknown"
        }
        if (-not [IO.Path]::IsPathRooted($folder.Path)) {
            Fail "the $($folder.Name) known folder is not an absolute path: '$($folder.Path)'"
        }
        if (-not (Test-Path -LiteralPath $folder.Path -PathType Container)) {
            Fail "the $($folder.Name) known folder is not an existing directory: '$($folder.Path)'"
        }
    }

    $roamingRoot = Resolve-FullPath -Path $RoamingRoot
    $localRoot = Resolve-FullPath -Path $LocalRoot
    $settingsDirectory = Join-Path $roamingRoot 'MuseScore'
    $settingsFilePath = Join-Path $settingsDirectory "$ProfileName.ini"
    $profileDirectory = Join-Path (Join-Path $localRoot 'MuseScore') $ProfileName

    $refusals = @()
    if (Test-Path -LiteralPath $settingsFilePath) {
        $refusals += "existing settings file $settingsFilePath"
    }
    if (Test-Path -LiteralPath $profileDirectory) {
        $refusals += "existing application-local profile directory $profileDirectory"
    }

    return @{
        ProfileName              = $ProfileName
        SettingsDirectory        = $settingsDirectory
        SettingsFilePath         = $settingsFilePath
        ProfileDirectory         = $profileDirectory
        LogDirectory             = Join-Path $profileDirectory 'logs'
        ApplicationDataRoot      = $roamingRoot
        LocalApplicationDataRoot = $localRoot
        RedirectEnvironment      = $RedirectEnvironment
        Refusals                 = $refusals
    }
}

function Assert-ProfilePlanUsable {
    param([Parameter(Mandatory = $true)][hashtable] $Plan)

    if ($Plan.Refusals.Count -eq 0) {
        return
    }
    Fail ("refusing to overwrite an existing development profile: " +
          ("{0}; the fresh-runner contract requires a clean profile and this helper never modifies or deletes existing state" -f ($Plan.Refusals -join '; ')))
}

function Assert-HostedRunnerContext {
    <#
        Preparing the profile means writing to the real Windows known folders. That is only
        acceptable on a fresh, disposable GitHub-hosted runner, which GitHub marks with
        GITHUB_ACTIONS=true and RUNNER_ENVIRONMENT=github-hosted. A self-hosted or interactive run
        could be sharing a developer's own development profile, so it is refused outright instead
        of redirecting environment variables the application ignores.
    #>
    param(
        [Parameter(Mandatory = $false)][string] $GitHubActions = $env:GITHUB_ACTIONS,
        [Parameter(Mandatory = $false)][string] $RunnerEnvironment = $env:RUNNER_ENVIRONMENT
    )

    if ($GitHubActions -ne 'true') {
        Fail ("refusing to prepare a real Windows profile outside GitHub Actions (GITHUB_ACTIONS is " +
              "'$GitHubActions', expected 'true'): a local or self-hosted run may share an owner's development profile")
    }
    if ($RunnerEnvironment -ne 'github-hosted') {
        Fail ("refusing to prepare a real Windows profile outside a GitHub-hosted runner (RUNNER_ENVIRONMENT is " +
              "'$RunnerEnvironment', expected 'github-hosted'): isolation comes from the fresh VM, not from environment redirection")
    }
}

function Get-KnownFolderPath {
    param([Parameter(Mandatory = $true)][System.Environment+SpecialFolder] $Folder)

    $path = [System.Environment]::GetFolderPath($Folder)
    if ([string]::IsNullOrWhiteSpace($path)) {
        Fail "the Windows $Folder known folder resolved to an empty path; the profile location is unknown"
    }
    return $path
}

function Get-ReviewedTestCase {
    <#
        Reads a reviewed testflow script from the source checkout and returns the test case
        name and step names it declares. Testflow scripts are JavaScript and declare
        `var testCase = { name: "...", steps: [{name: "...", func: ...}, ...] }`; this bounded
        scan takes the first `name: "..."` as the test case name and every following one, in
        order, as a step name. A script it cannot read this way returns $null so the caller
        fails the run instead of judging the report against guessed steps.
    #>
    param([Parameter(Mandatory = $true)][string] $Path)

    $text = [IO.File]::ReadAllText($Path)
    $nameMatches = @([regex]::Matches($text, 'name\s*:\s*"((?:[^"\\]|\\.)*)"'))
    if ($nameMatches.Count -lt 2) {
        return $null
    }

    $name = $nameMatches[0].Groups[1].Value
    $steps = @($nameMatches | Select-Object -Skip 1 | ForEach-Object { $_.Groups[1].Value })
    if ([string]::IsNullOrWhiteSpace($name) -or $steps.Count -eq 0) {
        return $null
    }

    return @{ Name = $name; Steps = $steps }
}

function Get-TestflowReportFailures {
    <#
        Checks one testflow report against the reviewed test case and returns the reasons it is
        not evidence that the reviewed steps ran to completion.

        TestCaseReport writes the report at the start of runTestCase(): a `Test:` header with
        the verbatim test case name, a `steps:` declaration of the whole step list, then one
        line per step transition. The report is accepted only when it is for the reviewed test
        case, declares exactly the reviewed step list, records every one of those steps as
        finished in order, and records no unsuccessful step and no aborted completion.
    #>
    param(
        [Parameter(Mandatory = $true)][string] $ReportPath,
        [Parameter(Mandatory = $true)][hashtable] $Reviewed
    )

    $failures = @()
    $lines = @([IO.File]::ReadAllLines($ReportPath))

    $testHeaders = @($lines | Where-Object { $_ -like 'Test: *' })
    if ($testHeaders.Count -ne 1) {
        $failures += "report $ReportPath has $($testHeaders.Count) 'Test:' header lines"
    } elseif ($testHeaders[0].Substring('Test:'.Length).Trim() -ne $Reviewed.Name) {
        $failures += "report $ReportPath is for the test case '$($testHeaders[0].Substring('Test:'.Length).Trim())', not the reviewed '$($Reviewed.Name)'"
    }

    $stepHeaders = @($lines | Where-Object { $_ -like 'steps:*' })
    if ($stepHeaders.Count -ne 1) {
        $failures += "report $ReportPath has $($stepHeaders.Count) 'steps:' declarations"
    } else {
        $declaredText = $stepHeaders[0].Substring('steps:'.Length).Trim()
        # Assigned with an explicit statement: an if-expression would unwrap a single step.
        $declaredSteps = @()
        if (-not [string]::IsNullOrWhiteSpace($declaredText)) {
            $declaredSteps = @($declaredText -split ' -> ')
        }
        if ($declaredSteps.Count -eq 0) {
            $failures += "report $ReportPath declares no steps"
        } elseif ($declaredSteps.Count -ne $Reviewed.Steps.Count) {
            $failures += "report $ReportPath declares $($declaredSteps.Count) steps, the reviewed test case declares $($Reviewed.Steps.Count)"
        } else {
            for ($i = 0; $i -lt $Reviewed.Steps.Count; $i++) {
                if ($declaredSteps[$i] -ne $Reviewed.Steps[$i]) {
                    $failures += "report $ReportPath declares step $($i + 1) as '$($declaredSteps[$i])', the reviewed test case declares '$($Reviewed.Steps[$i])'"
                    break
                }
            }
        }
    }

    $finishedSteps = @()
    $unsuccessfulSteps = @()
    foreach ($line in $lines) {
        $finishedMatch = [regex]::Match($line, '^  finished step: (?<name>.+?) \[\d+ msec\]$')
        if ($finishedMatch.Success) {
            $finishedSteps += $finishedMatch.Groups['name'].Value
            continue
        }
        if ($line -match '^  (error|abort|skipped) step: ' -or $line -match '^Test case aborted!') {
            $unsuccessfulSteps += $line.Trim()
        }
    }

    if ($finishedSteps.Count -eq 0) {
        $failures += "report $ReportPath records no finished step"
    } elseif ($finishedSteps.Count -ne $Reviewed.Steps.Count) {
        $failures += "report $ReportPath records $($finishedSteps.Count) finished steps, the reviewed test case declares $($Reviewed.Steps.Count)"
    } else {
        for ($i = 0; $i -lt $Reviewed.Steps.Count; $i++) {
            if ($finishedSteps[$i] -ne $Reviewed.Steps[$i]) {
                $failures += "report $ReportPath finished step $($i + 1) is '$($finishedSteps[$i])', the reviewed test case declares '$($Reviewed.Steps[$i])'"
                break
            }
        }
    }

    if ($unsuccessfulSteps.Count -gt 0) {
        $failures += "report $ReportPath records an unsuccessful step: $($unsuccessfulSteps -join '; ')"
    }

    return $failures
}

# Builds a child environment that clears developer Qt/QML overrides explicitly,
# restricts the application's search path on a real Windows host (the package's
# own directory plus the Windows system directories, nothing inherited from the
# runner's developer tooling), keeps the normal host PATH on the POSIX fixture
# sandbox, applies the documented software-rendering accommodation, and - only on
# the sandbox - the profile roots the stub should use. Returns the number of PATH
# entries and variables removed.
function New-ChildProcessStartInfo {
    param(
        [Parameter(Mandatory = $true)][string] $Executable,
        [Parameter(Mandatory = $true)][string] $WorkingDirectory,
        [Parameter(Mandatory = $true)][hashtable] $ProfilePlan,
        [string] $TestflowDataPath
    )

    if ([string]::IsNullOrWhiteSpace($TestflowDataPath)) {
        $TestflowDataPath = $script:TestflowDataRoot
    }

    $startInfo = [System.Diagnostics.ProcessStartInfo]::new()
    $startInfo.FileName = $Executable
    $startInfo.WorkingDirectory = $WorkingDirectory
    $startInfo.UseShellExecute = $false
    $startInfo.RedirectStandardOutput = $true
    $startInfo.RedirectStandardError = $true
    $startInfo.CreateNoWindow = $true

    $removedVariables = 0
    foreach ($name in $script:QtEnvironmentVariables) {
        if ($null -ne (Get-EnvValue -StartInfo $startInfo -Name $name)) {
            Remove-EnvValue -StartInfo $startInfo -Name $name
            $removedVariables++
        }
    }

    $pathSeparator = [IO.Path]::PathSeparator
    $pathValue = Get-EnvValue -StartInfo $startInfo -Name 'PATH'
    $removedPathEntries = 0
    $inheritedPathEntries = @()
    if ($null -ne $pathValue) {
        $inheritedPathEntries = @($pathValue -split [regex]::Escape($pathSeparator) | Where-Object { -not [string]::IsNullOrWhiteSpace($_) })
    }

    if ($script:IsWindowsHost) {
        # The application under test is the extracted package, so its search path holds only the
        # package's own directory and the Windows system directories. Visual Studio, Python,
        # OpenSSL, Git and other developer tool directories from the runner image must not be
        # reachable: a package that only starts because one of them is on PATH is not a
        # self-contained package. A standard runner image can still provide shared runtimes from
        # System32; that is a property of the image, not evidence about a minimal end-user Windows
        # installation. Only the child's environment is rebuilt here - the helper's own PATH and
        # tool environment are left untouched.
        $systemRoot = $env:SystemRoot
        if ([string]::IsNullOrWhiteSpace($systemRoot)) {
            Fail 'SystemRoot is not set; the application process search path cannot be built'
        }
        $applicationPath = @(
            (Split-Path -Parent $Executable)
            (Join-Path $systemRoot 'system32')
            $systemRoot
        )
        $removedPathEntries = $inheritedPathEntries.Count
        Set-EnvValue -StartInfo $startInfo -Name 'PATH' -Value ($applicationPath -join $pathSeparator)
        Write-Host "   application PATH: $($applicationPath -join $pathSeparator)"
    } elseif ($pathValue -ne $null) {
        # Fixture host: the stub needs the host's normal shell environment (sh, python3), so only
        # development Qt/QML search paths are removed.
        $kept = @()
        foreach ($entry in $inheritedPathEntries) {
            $isQt = $false
            foreach ($segment in ($entry -split '[\\/]')) {
                if ($segment -match '^(?i)qt') {
                    $isQt = $true
                    break
                }
            }
            if ($isQt) {
                Write-Host "   cleared Qt PATH entry: $entry"
                $removedPathEntries++
            } else {
                $kept += $entry
            }
        }
        Set-EnvValue -StartInfo $startInfo -Name 'PATH' -Value ($kept -join $pathSeparator)
    }

    # The application resolves its profile through the Windows known folders, so redirecting
    # APPDATA/LOCALAPPDATA on a real host would name a directory the application never opens.
    # Only the POSIX fixture sandbox hands its roots to the stub this way.
    if ($ProfilePlan.RedirectEnvironment) {
        Set-EnvValue -StartInfo $startInfo -Name 'APPDATA' -Value $ProfilePlan.ApplicationDataRoot
        Set-EnvValue -StartInfo $startInfo -Name 'LOCALAPPDATA' -Value $ProfilePlan.LocalApplicationDataRoot
    }
    Set-EnvValue -StartInfo $startInfo -Name 'MUSE_TESTFLOW_DATA_PATH' -Value $TestflowDataPath
    Set-EnvValue -StartInfo $startInfo -Name 'QT_QUICK_BACKEND' -Value 'software'
    Set-EnvValue -StartInfo $startInfo -Name 'QT_COMMAND_LINE_PARSER_NO_GUI_MESSAGE_BOXES' -Value '1'

    return @{
        StartInfo              = $startInfo
        RemovedVariables       = $removedVariables
        RemovedPathEntries     = $removedPathEntries
    }
}

function Test-ProcessExited {
    <#
        Exit state of a process, with no assumption: an unreadable state is reported and treated as
        not exited, so the caller resolves it instead of believing the process is gone.
    #>
    param([Parameter(Mandatory = $true)][System.Diagnostics.Process] $Process)

    try {
        return $Process.HasExited
    } catch {
        Write-Host "   the process exit state could not be read: $($_.Exception.Message)"
        return $false
    }
}

function Wait-ProcessExit {
    <#
        Bounded wait for an exit. $true means the process is known to have exited: the wait reported
        it, or the wait itself failed and the exit state is still readable and true. Any other
        outcome is $false, so the caller can fail the run instead of assuming progress.
    #>
    param(
        [Parameter(Mandatory = $true)][System.Diagnostics.Process] $Process,
        [Parameter(Mandatory = $true)][int] $TimeoutSeconds
    )

    try {
        return $Process.WaitForExit($TimeoutSeconds * 1000)
    } catch {
        Write-Host "   waiting for the process to exit failed: $($_.Exception.Message)"
        return (Test-ProcessExited -Process $Process)
    }
}

function Stop-ProcessTree {
    <#
        Terminates a process and all of its descendants with .NET's own tree kill and confirms the
        exit within a deadline. No external termination tool is started or waited on, so nothing
        here can block past that deadline. Returns $true only when the process is known to have
        exited; an unconfirmed termination is reported by the caller as a failed run.
    #>
    param([Parameter(Mandatory = $true)][System.Diagnostics.Process] $Process)

    if (Test-ProcessExited -Process $Process) {
        return $true
    }

    try {
        $Process.Kill($true)
    } catch {
        Write-Host "   process tree kill failed: $($_.Exception.Message)"
    }

    return (Wait-ProcessExit -Process $Process -TimeoutSeconds $script:KillTimeoutSeconds)
}
function Get-ProcessSnapshot {
    <#
        Captures the processes visible while a timed-out child is being resolved. Windows runners use
        Win32_Process so parent IDs and command lines identify the application tree; POSIX fixture
        hosts use Get-Process because Win32_Process is unavailable there.
    #>
    param([Parameter(Mandatory = $true)][int] $RootProcessId)

    $queryError = $null
    $processes = @()
    if ($script:IsWindowsHost) {
        try {
            $processes = @(Get-CimInstance -ClassName Win32_Process `
                    -OperationTimeoutSec $script:ProcessSnapshotTimeoutSeconds -ErrorAction Stop | ForEach-Object {
                    [ordered]@{
                        process_id        = [int] $_.ProcessId
                        parent_process_id = [int] $_.ParentProcessId
                        name              = [string] $_.Name
                        executable_path   = [string] $_.ExecutablePath
                        command_line      = [string] $_.CommandLine
                    }
                })
        } catch {
            $queryError = $_.Exception.Message
        }
    } else {
        try {
            $processes = @(Get-Process -ErrorAction Stop | ForEach-Object {
                    $path = ''
                    try {
                        $path = [string] $_.Path
                    } catch {
                        $path = ''
                    }
                    [ordered]@{
                        process_id        = [int] $_.Id
                        parent_process_id = $null
                        name              = [string] $_.ProcessName
                        executable_path   = $path
                        command_line      = $null
                    }
                })
        } catch {
            $queryError = $_.Exception.Message
        }
    }

    return [ordered]@{
        captured_at_utc = [DateTime]::UtcNow.ToString('o')
        root_process_id = $RootProcessId
        query_error     = $queryError
        processes       = $processes
    }
}

function Save-ProcessSnapshot {
    param(
        [Parameter(Mandatory = $true)][int] $RootProcessId,
        [Parameter(Mandatory = $true)][string] $Path
    )

    try {
        New-Item -ItemType Directory -Path (Split-Path -Parent $Path) -Force | Out-Null
        $snapshot = Get-ProcessSnapshot -RootProcessId $RootProcessId
        [IO.File]::WriteAllText($Path, ($snapshot | ConvertTo-Json -Depth 6), [Text.UTF8Encoding]::new($false))
        return $true
    } catch {
        Write-Host "   process snapshot failed: $($_.Exception.Message)"
        return $false
    }
}

function Copy-TestflowTimeoutDiagnostics {
    <#
        Copies the evidence that is otherwise easy to lose when a testflow process is terminated.
        This is called immediately after a timed-out testflow process returns from its bounded kill
        and output-drain path, before report validation or the next case starts. Collection has its
        own deadline and byte cap so a damaged profile or unexpectedly large log cannot hide the
        original timeout result.
    #>
    param(
        [Parameter(Mandatory = $true)][string] $Name,
        [Parameter(Mandatory = $true)][hashtable] $ProfilePlan,
        [Parameter(Mandatory = $true)][string] $TestflowDataPath,
        [Parameter(Mandatory = $true)][hashtable] $Result,
        [Parameter(Mandatory = $true)][string] $LogRoot
    )

    $safeName = $Name -replace '[^A-Za-z0-9_.-]', '_'
    $diagnosticRoot = Join-Path $LogRoot (Join-Path 'diagnostics' $safeName)
    $manifestPath = Join-Path $diagnosticRoot 'manifest.json'
    $stopwatch = [Diagnostics.Stopwatch]::StartNew()
    $deadline = [DateTime]::UtcNow.AddSeconds($script:TimeoutDiagnosticsSeconds)
    $copied = @()
    $missing = @()
    $errors = @()
    $bytesCopied = [long] 0
    $collectionTimedOut = $false

    $resultRecord = @{
        Root              = $diagnosticRoot
        Manifest          = $manifestPath
        Errors            = @()
        CollectionTimedOut = $false
        BytesCopied       = [long] 0
        ElapsedSeconds    = 0.0
    }
    try {
        New-Item -ItemType Directory -Path $diagnosticRoot -Force | Out-Null
    } catch {
        $resultRecord.Errors = @("diagnostic root: $($_.Exception.Message)")
        $stopwatch.Stop()
        $resultRecord.ElapsedSeconds = $stopwatch.Elapsed.TotalSeconds
        return $resultRecord
    }

    $items = @(
        @{ Label = 'stdout'; Source = $Result.StdoutLog; Kind = 'file' }
        @{ Label = 'stderr'; Source = $Result.StderrLog; Kind = 'file' }
        # Only the app's own log directory and the seeded settings file are retained from the fresh
        # profile. The rest of the profile is neither needed to diagnose a hang nor uploaded.
        @{ Label = 'profile-logs'; Source = $ProfilePlan.LogDirectory; Kind = 'directory' }
        @{ Label = 'profile-settings'; Source = $ProfilePlan.SettingsFilePath; Kind = 'file' }
        @{ Label = 'reports'; Source = (Join-Path $TestflowDataPath 'reports'); Kind = 'directory' }
        @{ Label = 'process'; Source = $Result.ProcessSnapshotRoot; Kind = 'directory' }
    )

    foreach ($item in $items) {
        if ([DateTime]::UtcNow -ge $deadline) {
            $collectionTimedOut = $true
            $errors += "collection deadline reached before $($item.Label)"
            break
        }

        $label = [string] $item.Label
        $source = [string] $item.Source
        $destination = Join-Path $diagnosticRoot $label
        $pathType = if ($item.Kind -eq 'file') { 'Leaf' } else { 'Container' }
        if ([string]::IsNullOrWhiteSpace($source) -or -not (Test-Path -LiteralPath $source -PathType $pathType)) {
            $missing += $label
            try {
                [IO.File]::WriteAllText(
                    (Join-Path $diagnosticRoot "$label.missing.txt"),
                    "Source was not present at timeout: $source",
                    [Text.UTF8Encoding]::new($false))
            } catch {
                $errors += "$label missing marker: $($_.Exception.Message)"
            }
            continue
        }

        try {
            if ($item.Kind -eq 'file') {
                $sourceInfo = Get-Item -LiteralPath $source -ErrorAction Stop
                $sourceLength = [long] $sourceInfo.Length
                if ($sourceLength -gt ($script:TimeoutDiagnosticsMaxBytes - $bytesCopied)) {
                    $errors += "$label exceeds the ${script:TimeoutDiagnosticsMaxBytes}-byte diagnostics cap"
                    continue
                }
                Copy-Item -LiteralPath $source -Destination ($destination + [IO.Path]::GetExtension($source)) -Force
                $bytesCopied += $sourceLength
                $copied += $label
            } else {
                New-Item -ItemType Directory -Path $destination -Force | Out-Null
                $directoryComplete = $true
                $enumerator = [IO.Directory]::EnumerateFiles(
                    $source, '*', [IO.SearchOption]::AllDirectories).GetEnumerator()
                try {
                    while ($enumerator.MoveNext()) {
                        if ([DateTime]::UtcNow -ge $deadline) {
                            $collectionTimedOut = $true
                            $directoryComplete = $false
                            $errors += "$label collection deadline reached"
                            break
                        }
                        $filePath = [string] $enumerator.Current
                        $fileInfo = Get-Item -LiteralPath $filePath -ErrorAction Stop
                        if (($fileInfo.Attributes -band [IO.FileAttributes]::ReparsePoint) -ne 0) {
                            $directoryComplete = $false
                            $errors += "$label skipped reparse-point file '$filePath'"
                            continue
                        }
                        $fileLength = [long] $fileInfo.Length
                        if ($fileLength -gt ($script:TimeoutDiagnosticsMaxBytes - $bytesCopied)) {
                            $directoryComplete = $false
                            $errors += "$label exceeded the ${script:TimeoutDiagnosticsMaxBytes}-byte diagnostics cap at '$filePath'"
                            break
                        }
                        $relativePath = [IO.Path]::GetRelativePath($source, $filePath)
                        $destinationPath = Join-Path $destination $relativePath
                        New-Item -ItemType Directory -Path (Split-Path -Parent $destinationPath) -Force | Out-Null
                        Copy-Item -LiteralPath $filePath -Destination $destinationPath -Force
                        $bytesCopied += $fileLength
                    }
                } finally {
                    $enumerator.Dispose()
                }
                if ($directoryComplete) {
                    $copied += $label
                }
            }
            if ([DateTime]::UtcNow -ge $deadline) {
                $collectionTimedOut = $true
                $errors += "$label collection exceeded its deadline"
            }
        } catch {
            $errors += "$($label): $($_.Exception.Message)"
        }
    }

    $stopwatch.Stop()
    $manifest = [ordered]@{
        name                   = $Name
        timed_out              = $Result.TimedOut
        diagnostic_root        = $diagnosticRoot
        stdout_log             = $Result.StdoutLog
        stderr_log             = $Result.StderrLog
        testflow_data          = $TestflowDataPath
        process_snapshots      = $Result.ProcessSnapshotRoot
        copied                 = @($copied)
        missing                = @($missing)
        errors                 = @($errors)
        collection_timed_out   = $collectionTimedOut
        collection_elapsed_sec = $stopwatch.Elapsed.TotalSeconds
        bytes_copied           = $bytesCopied
    }
    try {
        [IO.File]::WriteAllText($manifestPath, ($manifest | ConvertTo-Json -Depth 6), [Text.UTF8Encoding]::new($false))
    } catch {
        $errors += "manifest: $($_.Exception.Message)"
    }

    $resultRecord.Errors = @($errors)
    $resultRecord.CollectionTimedOut = $collectionTimedOut
    $resultRecord.BytesCopied = $bytesCopied
    $resultRecord.ElapsedSeconds = $stopwatch.Elapsed.TotalSeconds
    return $resultRecord
}


function Read-RedirectedOutput {
    <#
        Reads one redirected stream to its end within a deadline. A descendant process that inherited
        the write handle keeps the read pending, so an unfinished read is reported as incomplete
        output instead of being waited on.
    #>
    param(
        [Parameter(Mandatory = $true)][System.Threading.Tasks.Task[string]] $Task,
        [Parameter(Mandatory = $true)][string] $StreamName
    )

    try {
        if ($Task.Wait([TimeSpan]::FromSeconds($script:OutputDrainSeconds))) {
            return @{ Text = $Task.Result; Complete = $true }
        }
        Write-Host "   $StreamName did not reach end of stream within $($script:OutputDrainSeconds)s (a descendant process may still hold the pipe)"
        return @{ Text = ''; Complete = $false }
    } catch {
        Write-Host "   reading $StreamName failed: $($_.Exception.Message)"
        return @{ Text = ''; Complete = $false }
    }
}

function Invoke-BoundedProcess {
    param(
        [Parameter(Mandatory = $true)][string] $Name,
        [Parameter(Mandatory = $true)][string] $Executable,
        [Parameter(Mandatory = $true)][string[]] $Arguments,
        [Parameter(Mandatory = $true)][string] $WorkingDirectory,
        [Parameter(Mandatory = $true)][hashtable] $ProfilePlan,
        [Parameter(Mandatory = $true)][int] $TimeoutSeconds,
        [Parameter(Mandatory = $true)][string] $LogRoot,
        [string] $TestflowDataPath,
        [string] $ProcessSnapshotRoot = ''
    )

    $startInfoResult = New-ChildProcessStartInfo -Executable $Executable -WorkingDirectory $WorkingDirectory `
        -ProfilePlan $ProfilePlan -TestflowDataPath $TestflowDataPath
    $startInfo = $startInfoResult.StartInfo
    foreach ($argument in $Arguments) {
        $startInfo.ArgumentList.Add($argument)
    }

    $stdoutPath = Join-Path $LogRoot "$Name.stdout.log"
    $stderrPath = Join-Path $LogRoot "$Name.stderr.log"
    Write-Host "> $Executable $($Arguments -join ' ')"
    Write-Host "   timeout ${TimeoutSeconds}s, log $stdoutPath"

    if (-not [string]::IsNullOrWhiteSpace($ProcessSnapshotRoot)) {
        New-Item -ItemType Directory -Path $ProcessSnapshotRoot -Force | Out-Null
    }

    $process = [System.Diagnostics.Process]::new()
    $process.StartInfo = $startInfo
    $null = $process.Start()
    $stdoutTask = $process.StandardOutput.ReadToEndAsync()
    $stderrTask = $process.StandardError.ReadToEndAsync()

    $timedOut = $false
    $terminationConfirmed = $true
    if (-not $process.WaitForExit($TimeoutSeconds * 1000)) {
        $timedOut = $true
        if (-not [string]::IsNullOrWhiteSpace($ProcessSnapshotRoot)) {
            Save-ProcessSnapshot -RootProcessId $process.Id `
                -Path (Join-Path $ProcessSnapshotRoot 'process-before-termination.json') | Out-Null
        }
        Write-Host "   TIMEOUT after ${TimeoutSeconds}s; terminating the process tree"
        $terminationConfirmed = Stop-ProcessTree -Process $process
        if (-not $terminationConfirmed) {
            Add-Failure "$Name did not exit within ${TimeoutSeconds}s and its process tree could not be terminated within $($script:KillTimeoutSeconds)s; the run cannot be bounded (log $stdoutPath)"
        }
        if (-not [string]::IsNullOrWhiteSpace($ProcessSnapshotRoot)) {
            Save-ProcessSnapshot -RootProcessId $process.Id `
                -Path (Join-Path $ProcessSnapshotRoot 'process-after-termination.json') | Out-Null
        }
    }

    $stdoutResult = Read-RedirectedOutput -Task $stdoutTask -StreamName 'stdout'
    $stderrResult = Read-RedirectedOutput -Task $stderrTask -StreamName 'stderr'
    $stdout = $stdoutResult.Text
    $stderr = $stderrResult.Text

    [IO.File]::WriteAllText($stdoutPath, $stdout, [Text.UTF8Encoding]::new($false))
    [IO.File]::WriteAllText($stderrPath, $stderr, [Text.UTF8Encoding]::new($false))

    if (-not ($stdoutResult.Complete -and $stderrResult.Complete)) {
        Add-Failure "$Name output did not reach end of stream within $($script:OutputDrainSeconds)s after the process ended; the retained logs are incomplete ($stdoutPath)"
    }

    $exitCode = $null
    if (-not $timedOut) {
        $exitCode = $process.ExitCode
    }
    $process.Dispose()

    $terminationSummary = "process tree termination confirmed"
    if (-not $terminationConfirmed) {
        $terminationSummary = "process tree termination could NOT be confirmed; the run cannot be bounded"
    }

    return @{
        Name                 = $Name
        Executable           = $Executable
        Arguments            = $Arguments
        TimedOut             = $timedOut
        TerminationSummary   = $terminationSummary
        ExitCode             = $exitCode
        Stdout               = $stdout
        Stderr               = $stderr
        StdoutLog            = $stdoutPath
        StderrLog            = $stderrPath
        ProcessSnapshotRoot  = $ProcessSnapshotRoot
        RemovedPathEntries   = $startInfoResult.RemovedPathEntries
        RemovedVariables     = $startInfoResult.RemovedVariables
    }
}

# ---------------------------------------------------------------------------
# Testability hook: first-run profile contract
# ---------------------------------------------------------------------------
# Resolves and validates the profile contract the same way a real run does - the same profile name
# derivation, the same path layout and the same existing-profile refusal - for the profile sandbox
# under -OutputDirectory, and prints it as JSON. This exists because the refusal and the
# hosted-runner guard are unreachable from a POSIX fixture through the normal path (that path
# recreates its own sandbox first) and because a wrong profile path otherwise costs a full
# hosted build before it is detected. It is not a substitute for the hosted run of the installed
# binary, and it exercises helper logic only - no packaged-application evidence is claimed.
if ($ExportProfilePlan) {
    if ([string]::IsNullOrWhiteSpace($SourceDirectory)) {
        Fail '-ExportProfilePlan requires -SourceDirectory'
    }
    if ([string]::IsNullOrWhiteSpace($OutputDirectory)) {
        Fail '-ExportProfilePlan requires -OutputDirectory'
    }
    Assert-HostedRunnerContext
    $planVersion = Read-VersionCmake -Path (Join-Path $SourceDirectory 'version.cmake')
    if ($null -eq $planVersion) {
        Fail "-SourceDirectory does not provide version.cmake: $SourceDirectory"
    }
    $sandboxRoot = Resolve-FullPath -Path $OutputDirectory
    $plan = Resolve-ProfilePlan `
        -RoamingRoot (Join-Path $sandboxRoot $script:ProfileSandboxRoamingRelative) `
        -LocalRoot (Join-Path $sandboxRoot $script:ProfileSandboxLocalRelative) `
        -ProfileName (Get-DevelopmentProfileName -Version $planVersion)
    Assert-ProfilePlanUsable -Plan $plan
    ConvertTo-Json -Depth 4 -InputObject ([ordered]@{
            profile_name      = $plan.ProfileName
            settings_file     = $plan.SettingsFilePath
            profile_directory = $plan.ProfileDirectory
            log_directory     = $plan.LogDirectory
        })
    exit 0
}

