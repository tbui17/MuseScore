$sumsMatch = [regex]::Match($sumsLines[0], '^([0-9a-f]{64})  (\S+)$')
if (-not $sumsMatch.Success) {
    Fail "SHA256SUMS.txt line is not '<lowercase sha256>  <filename>': $($sumsLines[0])"
