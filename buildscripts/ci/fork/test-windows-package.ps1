# 3. GUI testflow: mandatory TC11 + TC14, plus the exact TC15 feature fixture when present
# ---------------------------------------------------------------------------
Write-Section 'GUI testflow regression tests'
foreach ($scriptName in $script:RequiredTestScripts) {
    $extractedScript = Join-Path $extractRoot (Join-Path 'testflowscripts' $scriptName)
    if (-not (Test-Path -LiteralPath $extractedScript -PathType Leaf)) {
        Add-Failure "package does not contain the installed test script testflowscripts/$scriptName"
        continue
    }

    $sourceScript = Join-Path $sourceRoot (Join-Path 'share/testflowscripts' $scriptName)
    if (-not (Test-Path -LiteralPath $sourceScript -PathType Leaf)) {
        # Running the packaged copy would test whatever the package happens to contain
        # instead of the reviewed test case, so a missing reviewed script fails the run.
        Add-Failure "the reviewed script share/testflowscripts/$scriptName is missing from -SourceDirectory; refusing to run the packaged copy instead"
        continue
    }
    $sourceSha256 = Get-Sha256 -Path $sourceScript
    $packagedSha256 = Get-Sha256 -Path $extractedScript
    if ($sourceSha256 -ne $packagedSha256) {
        Add-Failure "installed testflowscripts/$scriptName differs from the reviewed script at source_sha"
        continue
    }

    $reviewed = Get-ReviewedTestCase -Path $sourceScript
    if ($null -eq $reviewed) {
        Add-Failure "the reviewed script share/testflowscripts/$scriptName declares no readable test case name and step list; refusing to judge the run against it"
        continue
    }

    # Testflow::runTestCase() calls TestCaseReport::beginReport(), which creates
    # <MUSE_TESTFLOW_DATA_PATH>/reports and writes one report there for the executed case. The
    # report file name is escaped for the file system (a test case name may contain characters
    # that are not valid in a Windows file name), so an actual report must be found and its
    # content must show the reviewed steps running to completion; a zero exit status alone, or
    # a bare reports directory, cannot distinguish that from a pass without evidence.
    $reportsRoot = Join-Path $script:TestflowDataRoot 'reports'
    if (Test-Path -LiteralPath $reportsRoot) {
        Remove-Item -LiteralPath $reportsRoot -Recurse -Force
    }

    $processName = "gui-" + ($scriptName -replace '\.js$', '')
    $processSnapshotRoot = Join-Path $logRoot (Join-Path 'process-snapshots' $processName)
    $result = Invoke-BoundedProcess -Name $processName -Executable $executableFullPath `
        -Arguments @('--test-case-gui', $extractedScript) `
        -WorkingDirectory $extractRoot -ProfilePlan $profilePlan `
        -TimeoutSeconds $GuiTimeoutSeconds -LogRoot $logRoot -ProcessSnapshotRoot $processSnapshotRoot
    $timeoutDiagnostics = $null
    if ($result.TimedOut) {
        $diagnosticRoot = Join-Path $logRoot (Join-Path 'diagnostics' ($processName -replace '[^A-Za-z0-9_.-]', '_'))
        try {
            $timeoutDiagnostics = Copy-TestflowTimeoutDiagnostics -Name $processName `
                -ProfilePlan $profilePlan -TestflowDataPath $script:TestflowDataRoot `
                -Result $result -LogRoot $logRoot
        } catch {
            $timeoutDiagnostics = @{
                Root = $diagnosticRoot
                Manifest = $null
                Errors = @("collector: $($_.Exception.Message)")
            }
        }
        if ($timeoutDiagnostics.Errors.Count -gt 0) {
            Add-Failure "$scriptName timeout diagnostics were incomplete: $($timeoutDiagnostics.Errors -join '; ') (original timeout preserved)"
        }
    }

    $recordedReports = @()
    if (Test-Path -LiteralPath $reportsRoot -PathType Container) {
        $recordedReports = @(Get-ChildItem -LiteralPath $reportsRoot -File -ErrorAction SilentlyContinue)
    }

    $ok = $true
    if ($result.TimedOut) {
        Add-Failure "$scriptName timed out after ${GuiTimeoutSeconds}s; $($result.TerminationSummary) (diagnostics $($timeoutDiagnostics.Root); log $($result.StdoutLog))"
        $ok = $false
    } elseif ($result.ExitCode -ne 0) {
        Add-Failure "$scriptName failed with exit code $($result.ExitCode) (log $($result.StdoutLog))"
        $ok = $false
    } elseif ($recordedReports.Count -ne 1) {
        Add-Failure "$scriptName exited 0 but recorded $($recordedReports.Count) testflow report file(s); the reviewed test case did not run (log $($result.StdoutLog))"
        $ok = $false
    } else {
        $reportFileName = $recordedReports[0].Name
        if ($recordedReports[0].Extension -ne '.txt' -or $reportFileName -notmatch '^[^<>:"/\\|?*\x00-\x1f]+$') {
            Add-Failure "$scriptName wrote a report whose file name is not filesystem-safe: '$reportFileName'"
            $ok = $false
        }
        foreach ($reportFailure in @(Get-TestflowReportFailures -ReportPath $recordedReports[0].FullName -Reviewed $reviewed)) {
            Add-Failure "$scriptName : $reportFailure"
            $ok = $false
        }
        if ($ok) {
            Write-Host "$scriptName passed (exit 0, report '$reportFileName' declares and finished the reviewed step list)"
        }
    }
    # Copy any recorded testflow report into the uploaded log directory for diagnosis.
    foreach ($recordedReport in $recordedReports) {
        Copy-Item -LiteralPath $recordedReport.FullName -Destination (Join-Path $logRoot ("testflow-" + $recordedReport.Name)) -Force -ErrorAction SilentlyContinue
    }
    Add-Result -Result @{ name = $scriptName; command = '--test-case-gui'; argv = @('--test-case-gui', $extractedScript); exit_code = $result.ExitCode; timed_out = $result.TimedOut; ok = $ok; recorded_reports = @($recordedReports | ForEach-Object { $_.Name }); diagnostics = if ($null -eq $timeoutDiagnostics) { $null } else { $timeoutDiagnostics.Root }; log = $result.StdoutLog }
}

# ---------------------------------------------------------------------------
# 4. Testflow report and status contract probes
# ---------------------------------------------------------------------------
# Tiny trusted scripts, written by this helper into its own output directory, run through the
# installed application to exercise report/status semantics the reviewed TC11/TC14 scripts do
# not reach: a test case name that must be escaped before it can become a file name, a run
# whose report cannot be created, a test case without steps, and an aborted test case. Each
# probe is timeout-bounded and judged by its exit status (and, where one must exist, by its
# report). The GUI runner exits through _exit(status == Finished ? 0 : 1), so an expected
# rejection is exit 1 exactly: any other nonzero status is a crash or an unexpected exit and
# fails the probe instead of counting as a correct rejection. These probes are not a substitute
# for the reviewed test cases; only the hosted run of the installed binary is evidence.
Write-Section 'Testflow report and status contract probes (real application)'

$probeRoot = Join-Path $outputRoot 'probes'
if (Test-Path -LiteralPath $probeRoot) {
    Remove-Item -LiteralPath $probeRoot -Recurse -Force
}
New-Item -ItemType Directory -Path $probeRoot -Force | Out-Null

$probeSources = [ordered]@{
    'finished' = @'
var testCase = {
    name: "helper probe: trivially finished case",
    description: "helper-generated probe, no reviewed assertions",
    steps: [
        {name: "Trivial step", func: function() {}}
    ]
};
function main()
{
    api.testflow.runTestCase(testCase)
}
'@
    'empty' = @'
var testCase = {
    name: "helper probe: case without steps",
    description: "helper-generated probe, no reviewed assertions",
    steps: []
};
function main()
{
    api.testflow.runTestCase(testCase)
}
'@
    'aborted' = @'
var testCase = {
    name: "helper probe: aborted case",
    description: "helper-generated probe, no reviewed assertions",
    steps: [
        {name: "Abort the run", func: function() {
            api.testflow.abort()
        }}
    ]
};
function main()
{
    api.testflow.runTestCase(testCase)
}
'@
}
$probeScripts = @{}
foreach ($probeName in $probeSources.Keys) {
    $probeScriptPath = Join-Path $probeRoot "$probeName.js"
    [IO.File]::WriteAllText($probeScriptPath, $probeSources[$probeName], [Text.UTF8Encoding]::new($false))
    $probeScripts[$probeName] = $probeScriptPath
}

function Invoke-TestflowProbe {
    param(
        [Parameter(Mandatory = $true)][string] $Name,
        [Parameter(Mandatory = $true)][string] $ScriptPath,
        [Parameter(Mandatory = $true)][string] $DataRoot
    )

    $processName = "probe-" + $Name
    $processSnapshotRoot = Join-Path $logRoot (Join-Path 'process-snapshots' $processName)
    $result = Invoke-BoundedProcess -Name $processName -Executable $executableFullPath `
        -Arguments @('--test-case-gui', $ScriptPath) `
        -WorkingDirectory $extractRoot -ProfilePlan $profilePlan `
        -TimeoutSeconds $GuiTimeoutSeconds -LogRoot $logRoot -TestflowDataPath $DataRoot `
        -ProcessSnapshotRoot $processSnapshotRoot
    if ($result.TimedOut) {
        $diagnosticRoot = Join-Path $logRoot (Join-Path 'diagnostics' ($processName -replace '[^A-Za-z0-9_.-]', '_'))
        try {
            $result.TimeoutDiagnostics = Copy-TestflowTimeoutDiagnostics -Name $processName `
                -ProfilePlan $profilePlan -TestflowDataPath $DataRoot `
                -Result $result -LogRoot $logRoot
        } catch {
            $result.TimeoutDiagnostics = @{
                Root = $diagnosticRoot
                Manifest = $null
                Errors = @("collector: $($_.Exception.Message)")
            }
        }
        if ($result.TimeoutDiagnostics.Errors.Count -gt 0) {
            Add-Failure "$processName timeout diagnostics were incomplete: $($result.TimeoutDiagnostics.Errors -join '; ') (original timeout preserved)"
        }
    }
    return $result
}

# Probe 1: the case name contains ':', which is not valid in a Windows file name. The run must
# still exit 0 and produce exactly one report whose file name is safe and whose content records
# the declared case name and step as finished.
$finishedDataRoot = Join-Path $probeRoot 'data-finished'
$result = Invoke-TestflowProbe -Name 'finished' -ScriptPath $probeScripts['finished'] -DataRoot $finishedDataRoot
$probeReports = @(Get-ChildItem -LiteralPath (Join-Path $finishedDataRoot 'reports') -File -ErrorAction SilentlyContinue)
$probeOk = $false
if ($result.TimedOut) {
    Add-Failure "probe finished timed out after ${GuiTimeoutSeconds}s; $($result.TerminationSummary) (diagnostics $($result.TimeoutDiagnostics.Root); log $($result.StdoutLog))"
} elseif ($result.ExitCode -ne 0) {
    Add-Failure "probe finished: a case that finishes every step must exit 0, got $($result.ExitCode) (log $($result.StdoutLog))"
} elseif ($probeReports.Count -ne 1) {
    Add-Failure "probe finished: expected one report under $finishedDataRoot, found $($probeReports.Count); a test case name that is not escaped cannot be written as a file name (log $($result.StdoutLog))"
} else {
    $probeReviewed = @{ Name = 'helper probe: trivially finished case'; Steps = @('Trivial step') }
    $probeFailures = @(Get-TestflowReportFailures -ReportPath $probeReports[0].FullName -Reviewed $probeReviewed)
    if ($probeReports[0].Name -notmatch '^[^<>:"/\\|?*\x00-\x1f]+$') {
        Add-Failure "probe finished: report file name is not filesystem-safe: '$($probeReports[0].Name)'"
    } elseif ($probeFailures.Count -gt 0) {
        Add-Failure "probe finished: $($probeFailures -join '; ')"
    } else {
        $probeOk = $true
        Write-Host "probe finished passed (exit 0, report '$($probeReports[0].Name)' records the finished step)"
    }
}
Add-Result -Result @{ name = 'probe-finished'; command = '--test-case-gui'; argv = @('--test-case-gui', $probeScripts['finished']); exit_code = $result.ExitCode; timed_out = $result.TimedOut; ok = $probeOk; diagnostics = if ($result.ContainsKey('TimeoutDiagnostics')) { $result.TimeoutDiagnostics.Root } else { $null }; log = $result.StdoutLog }

