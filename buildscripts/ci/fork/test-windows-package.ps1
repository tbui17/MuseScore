$headSha = Get-GitHead -Directory $sourceRoot
if ($headSha.ToLowerInvariant() -ne $manifestSourceSha.ToLowerInvariant()) {
    Fail "-SourceDirectory HEAD ($headSha) does not match manifest source_sha ($manifestSourceSha)"
