#!/usr/bin/env pwsh
# SPDX-License-Identifier: GPL-3.0-only
#
# MuseScore fork CI: Windows application package helper.
#
# Turns an installed MuseScore tree (cmake --install output) into exactly one
# unsigned, extract-and-run ZIP plus external SHA256SUMS.txt and
# build-manifest.json.
#
# Format contract:
#   * ZIP archive. This is NOT an installer, NOT an MSI and NOT the PortableApps
#     build. It is an ordinary application archive: extract and run bin/MuseScoreStudio5.exe.
#   * The install tree is never renamed and never mutated. A separate staging
#     copy is not used; the archive is read directly from the install directory.
#   * build.release / any build tree is never packaged.
#
# Package identity: <owner>-<repository>-<application_version>-<arch>-<source_sha12>-unsigned.zip
# A source branch name never becomes part of a path; only the resolved SHA does.
#
# Usage:
#   pwsh -File buildscripts/ci/fork/package-windows.ps1 `
#       -SourceDirectory  <repo checkout at source_sha> `
#       -InstallDirectory <install prefix root> `
#       -OutputDirectory  <dir that receives zip + SHA256SUMS.txt + build-manifest.json> `
#       -ProvenancePath   <JSON written by the Windows build helper>
#
#   pwsh -File buildscripts/ci/fork/package-windows.ps1 -ExportResourceExpectations
#       prints the default structural resource expectations as JSON (testability hook).

[CmdletBinding()]
param(
    [string] $SourceDirectory,
    [string] $InstallDirectory,
    [string] $OutputDirectory,
    [string] $ProvenancePath,
    [ValidateSet('x64', 'arm64')]
    [string] $Architecture = 'x64',
    [string[]] $AdditionalResourceExpectation = @(),
    [switch] $ExportResourceExpectations
)

$ErrorActionPreference = 'Stop'
Set-StrictMode -Version Latest

$script:IsWindowsHost = ($env:OS -eq 'Windows_NT')

# Identity fields that MUST come from the build helper's provenance file.
# The manifest is not allowed to invent any of these.
$script:ProvenanceRequiredKeys = @(
    'repository'
    'requested_source_ref'
    'source_sha'
    'framework_url'
    'framework_sha'
    'workflow_sha'
    'run_id'
    'run_attempt'
    'application_version'
    'channel'
    'build_type'
    'features'
    'toolchain'
    'dependency_lock'
)

